import { Column, Entity, PrimaryGeneratedColumn } from 'typeorm';

/** The tables of D50. Why each exists, and the rules the database holds of them, is in
 * `1763000000000-ShiftFuelForecast.ts`. */

/** numeric arrives from pg as a string; a figure on the wire should be a number. */
const asNumber = {
  to: (v: number | null | undefined) => v,
  from: (v: string | null) => (v === null || v === undefined ? null : Number(v)),
};

@Entity('legacy_shift_metric')
export class LegacyShiftMetric {
  @PrimaryGeneratedColumn('uuid') id: string;
  @Column({ name: 'tenant_id', type: 'text' }) tenantId: string;
  @Column({ name: 'source_system', type: 'text' }) sourceSystem: string;
  @Column({ name: 'external_id', type: 'text' }) externalId: string;
  @Column({ type: 'date' }) sdate: string;
  @Column({ type: 'smallint' }) shift: 1 | 2;
  @Column({ name: 'fuel_l', type: 'numeric', nullable: true, transformer: asNumber }) fuelL: number | null;
  @Column({ name: 'work_hrs', type: 'numeric', nullable: true, transformer: asNumber }) workHrs: number | null;
  @Column({ name: 'legacy_updated_at', type: 'timestamptz', nullable: true }) legacyUpdatedAt: Date | null;
  @Column({ name: 'synced_at', type: 'timestamptz' }) syncedAt: Date;
}

@Entity('shift_fuel_forecast')
export class ShiftFuelForecast {
  @PrimaryGeneratedColumn('uuid') id: string;
  @Column({ name: 'tenant_id', type: 'text' }) tenantId: string;
  @Column({ name: 'source_system', type: 'text' }) sourceSystem: string;
  @Column({ name: 'external_id', type: 'text' }) externalId: string;
  @Column({ type: 'date' }) sdate: string;
  @Column({ type: 'smallint' }) shift: 1 | 2;
  @Column({ name: 'predicted_l', type: 'numeric', transformer: asNumber }) predictedL: number;
  @Column({ type: 'text' }) method: string;
  @Column({ name: 'inputs_through', type: 'date', nullable: true }) inputsThrough: string | null;
  @Column({ name: 'issued_at', type: 'timestamptz' }) issuedAt: Date;
  /** Generated by the database from `sdate` and `shift`; never written from here. */
  @Column({ name: 'starts_at', type: 'timestamptz', insert: false, update: false }) startsAt: Date;
  @Column({ name: 'ends_at', type: 'timestamptz', insert: false, update: false }) endsAt: Date;
}

export const SHIFT_FUEL_ENTITIES = [LegacyShiftMetric, ShiftFuelForecast];
